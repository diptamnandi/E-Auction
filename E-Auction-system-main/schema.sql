-- 1. USERS Table
CREATE TABLE USERS (
    USER_ID NUMBER PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    PHONE_NO VARCHAR2(20),
    ADDRESS VARCHAR2(255),
    SECURITY_QUESTION VARCHAR2(255),
    SECURITY_ANSWER_HASH VARCHAR2(255)
);

CREATE SEQUENCE USERS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER USERS_TRG
BEFORE INSERT ON USERS
FOR EACH ROW
BEGIN
    IF :NEW.USER_ID IS NULL THEN
        SELECT USERS_SEQ.NEXTVAL INTO :NEW.USER_ID FROM DUAL;
    END IF;
END;
/

-- 2. ITEMS Table
CREATE TABLE ITEMS (
    ITEM_ID NUMBER PRIMARY KEY,
    SELLER_ID NUMBER NOT NULL,
    NAME VARCHAR2(150) NOT NULL,
    DESCRIPTION VARCHAR2(1000),
    CATEGORY VARCHAR2(100),
    IMAGE_URL VARCHAR2(500),
    CONSTRAINT FK_ITEMS_SELLER FOREIGN KEY (SELLER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE SEQUENCE ITEMS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER ITEMS_TRG
BEFORE INSERT ON ITEMS
FOR EACH ROW
BEGIN
    IF :NEW.ITEM_ID IS NULL THEN
        SELECT ITEMS_SEQ.NEXTVAL INTO :NEW.ITEM_ID FROM DUAL;
    END IF;
END;
/

-- 3. AUCTIONS Table
CREATE TABLE AUCTIONS (
    AUCTION_ID NUMBER PRIMARY KEY,
    ITEM_ID NUMBER NOT NULL,
    STARTING_BID NUMBER(12, 2) NOT NULL,
    HIGHEST_BID NUMBER(12, 2) DEFAULT 0,
    START_TIME TIMESTAMP NOT NULL,
    END_TIME TIMESTAMP NOT NULL,
    STATUS VARCHAR2(30) DEFAULT 'PENDING',
    CONSTRAINT FK_AUCTIONS_ITEM FOREIGN KEY (ITEM_ID) REFERENCES ITEMS(ITEM_ID) ON DELETE CASCADE
);

CREATE SEQUENCE AUCTIONS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER AUCTIONS_TRG
BEFORE INSERT ON AUCTIONS
FOR EACH ROW
BEGIN
    IF :NEW.AUCTION_ID IS NULL THEN
        SELECT AUCTIONS_SEQ.NEXTVAL INTO :NEW.AUCTION_ID FROM DUAL;
    END IF;
END;
/

-- 4. BIDS Table
CREATE TABLE BIDS (
    BID_ID NUMBER PRIMARY KEY,
    AUCTION_ID NUMBER NOT NULL,
    BIDDER_ID NUMBER NOT NULL,
    BID_AMOUNT NUMBER(12, 2) NOT NULL,
    BID_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_BIDS_AUCTION FOREIGN KEY (AUCTION_ID) REFERENCES AUCTIONS(AUCTION_ID) ON DELETE CASCADE,
    CONSTRAINT FK_BIDS_BIDDER FOREIGN KEY (BIDDER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

CREATE SEQUENCE BIDS_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE OR REPLACE TRIGGER BIDS_TRG
BEFORE INSERT ON BIDS
FOR EACH ROW
BEGIN
    IF :NEW.BID_ID IS NULL THEN
        SELECT BIDS_SEQ.NEXTVAL INTO :NEW.BID_ID FROM DUAL;
    END IF;
END;
